import 'package:flutter_test/flutter_test.dart';
import 'package:ai_accounting/services/local_parser_service.dart';

/// 本地解析引擎测试 — 与 server_simple.py _verify_parser.py 镜像同一张用例表
/// （today 固定 2026-10-16 周五）
void main() {
  final today = DateTime(2026, 10, 16);

  void check(String text, String expDate, double expAmt, String expRemark,
      String expType, String expCat, String expSub) {
    final b = LocalParserService.parse(text, now: today);
    final got = '${b.date}|${b.amount}|${b.remark}|${b.type}|${b.category}|${b.subcategory}';
    final exp = '$expDate|$expAmt|$expRemark|$expType|$expCat|$expSub';
    expect(got, exp, reason: '输入: $text');
  }

  group('日期解析', () {
    test('周日/星期X/礼拜X', () {
      check('周日晚餐花了18', '2026-10-11', 18.0, '晚餐', '支出', '餐饮', '三餐');
      check('星期日买水果花了30', '2026-10-11', 30.0, '水果', '支出', '餐饮', '水果');
      check('周天吃饭花了20', '2026-10-11', 20.0, '吃饭', '支出', '餐饮', '三餐');
      check('礼拜日买菜花了15', '2026-10-11', 15.0, '买菜', '支出', '餐饮', '买菜');
      check('周一吃饭花了6块', '2026-10-12', 6.0, '吃饭', '支出', '餐饮', '三餐');
      check('上周五看电影花了60', '2026-10-09', 60.0, '看电影', '支出', '娱乐', '电影');
      check('上周三买水果', '2026-10-07', 0.0, '水果', '支出', '餐饮', '水果');
    });

    test('大前天/后天/N天后', () {
      check('大前天买书花了50', '2026-10-13', 50.0, '买书', '支出', '购物', '');
      check('后天交房租2000', '2026-10-18', 2000.0, '房租', '支出', '居住', '房租');
      check('3天后交房租', '2026-10-19', 0.0, '房租', '支出', '居住', '房租');
    });

    test('裸 N 号（最近一次语义）', () {
      check('16号交房租2000', '2026-10-16', 2000.0, '房租', '支出', '居住', '房租');
      check('15号买牛奶花了10块', '2026-10-15', 10.0, '牛奶', '支出', '餐饮', '饮料');
      check('17号充话费50', '2026-09-17', 50.0, '话费', '支出', '居住', '宽带通信');
    });
  });

  group('备注提取', () {
    test('日期/金额/动词全部剥净', () {
      check('今天中午吃黄焖鸡花了25元', '2026-10-16', 25.0, '黄焖鸡', '支出', '餐饮', '三餐');
      check('买了水果花了30', '2026-10-16', 30.0, '水果', '支出', '餐饮', '水果');
      check('买了面膜花了50', '2026-10-16', 50.0, '面膜', '支出', '购物', '美妆护肤');
      check('昨天打车去公司花了22', '2026-10-15', 22.0, '打车去公司', '支出', '交通', '打车');
      check('交了2000房租押金500', '2026-10-16', 2000.0, '房租押金', '支出', '居住', '房租');
    });

    test('开头动词剥后保留核心名词', () {
      check('吃辣火锅花了80', '2026-10-16', 80.0, '辣火锅', '支出', '餐饮', '三餐');
    });
  });

  group('同音字容错', () {
    test('料→了 快→块', () {
      check('花料18块吃面', '2026-10-16', 18.0, '吃面', '支出', '餐饮', '三餐');
      check('买料一杯奶茶25', '2026-10-16', 25.0, '奶茶', '支出', '餐饮', '饮料');
    });

    test('辣 不被误改', () {
      check('吃辣火锅花了80', '2026-10-16', 80.0, '辣火锅', '支出', '餐饮', '三餐');
    });
  });

  group('收入', () {
    test('工资/奖金/兼职', () {
      check('收到工资5000', '2026-10-16', 5000.0, '工资', '收入', '薪资', '工资');
      check('发奖金了2000', '2026-10-16', 2000.0, '奖金', '收入', '薪资', '奖金');
      check('兼职赚了300', '2026-10-16', 300.0, '兼职', '收入', '薪资', '兼职');
    });
  });

  group('分类归属', () {
    test('关键词优先级', () {
      check('请客吃饭花了120', '2026-10-16', 120.0, '客吃饭', '支出', '人情', '');
      check('买感冒药花了25', '2026-10-16', 25.0, '感冒药', '支出', '医疗', '药品');
      check('交交通卡50', '2026-10-16', 50.0, '交通卡', '支出', '交通', '公交');
      check('充游戏会员30', '2026-10-16', 30.0, '游戏会员', '支出', '娱乐', '游戏');
      check('宽带费100', '2026-10-16', 100.0, '宽带费', '支出', '居住', '宽带通信');
    });
  });

  group('空输入', () {
    test('空文本回退', () {
      final b = LocalParserService.parse('   ', now: today);
      expect(b.category, '其他');
      expect(b.amount, 0);
    });
  });
}
