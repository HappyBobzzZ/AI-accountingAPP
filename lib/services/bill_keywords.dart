  /// 同音字容错归一化：输入法语音识别常见错字 → 修正
  /// 与 server_simple.py normalize() 保持一致
  static String normalize(String text) {
    // 动词+"了" 被识别成 "料/啦/拉/勒"：花了→花料、买了→买啦 …
    // 故意不含"辣"（避免"吃辣"被误改）
    var t = text.replaceAllMapped(
      RegExp(r'([花买交付收充存吃喝用转发缴赚捐还])(料|啦|拉|勒)'),
      (m) => '${m.group(1)}了',
    );
    // 数字+"块" 被识别成 "快"：三快→三块、50快→50块
    t = t.replaceAllMapped(
      RegExp(r'([零〇一二两三四五六七八九十百千万亿\d]+)快(钱?)'),
      (m) => '${m.group(1)}块${m.group(2)}',
    );
    return t;
  }

